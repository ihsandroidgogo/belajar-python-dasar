# Contoh Dasar Variabel di Python

nama = "Ihsan"
umur = 31
tinggi = 170
isTrue = True

print(f"Nama: {nama}, Umur: {umur}, Tinggi: {tinggi}, Is True: {isTrue}")
print(type(nama))
print(type(umur))
print(type(tinggi))
print(type(isTrue))

teks = """Ini adalah
string yang terdiri
dari banyak baris"""

print(teks)

# Multiple Assignment
x, y, z = 10, 20, 30
print(f"x: {x}, y: {y}, z: {z}")

# Mengubah tipe data variabel
nama_lengkap = "Muhammad Ihsan"
print(nama_lengkap)
print(f"Tipe Data: {type(nama_lengkap)}")
nama_lengkap = "Ayana Shahab"
print(nama_lengkap)