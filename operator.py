# Operator Assignment
x = 10    # variabel awal
x += 5    # sama dengan x = x + 5  -> 15
x -= 3    # sama dengan x = x - 3  -> 12
x *= 2    # sama dengan x = x * 2  -> 24
x /= 2    # sama dengan x = x / 2  -> 12

